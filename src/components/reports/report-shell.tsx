'use client'

import * as React from 'react'
import { toast } from 'sonner'
import { DownloadIcon, MonitorIcon, PrinterIcon } from 'lucide-react'
import { PageHeader } from '@/components/shared/page-header'
import { useCan } from '@/components/shared/role-gate'
import { Button } from '@/components/ui/button'
import { Segmented } from '@/components/ui/controls'
import { DropdownMenu, DropdownMenuContent, DropdownMenuItem, DropdownMenuLabel, DropdownMenuSeparator, DropdownMenuTrigger } from '@/components/ui/menus'
import { downloadTextFile, toCsv } from '@/lib/utils'

export interface ReportShellProps {
  title: string
  description: string
  filters?: React.ReactNode
  /** Screen view: chart + table. */
  children: React.ReactNode
  /** Print preview: official document(s). */
  document: React.ReactNode
  csv: () => (string | number)[][]
  fileName: string
}

export function ReportShell({ title, description, filters, children, document, csv, fileName }: ReportShellProps) {
  const [view, setView] = React.useState<'screen' | 'print'>('screen')
  const can = useCan()
  return (
    <>
      <PageHeader
        title={title}
        description={description}
        actions={
          <>
            <Segmented
              label="View"
              value={view}
              onChange={setView}
              options={[
                { value: 'screen', label: 'Report', icon: <MonitorIcon aria-hidden /> },
                { value: 'print', label: 'Print preview', icon: <PrinterIcon aria-hidden /> },
              ]}
            />
            {view === 'print' ? (
              <Button onClick={() => window.print()}>
                <PrinterIcon /> Print
              </Button>
            ) : null}
            {can('reports.export') ? (
              <DropdownMenu>
                <DropdownMenuTrigger asChild>
                  <Button variant="secondary">
                    <DownloadIcon /> Export
                  </Button>
                </DropdownMenuTrigger>
                <DropdownMenuContent align="end">
                  <DropdownMenuLabel>Download as</DropdownMenuLabel>
                  <DropdownMenuSeparator />
                  <DropdownMenuItem onSelect={() => downloadTextFile(`${fileName}.csv`, toCsv(csv()))}>CSV (spreadsheet)</DropdownMenuItem>
                  <DropdownMenuItem onSelect={() => toast.info('Excel export will be generated by the server once the backend is connected. Use CSV for now.')}>Excel (.xlsx)</DropdownMenuItem>
                  <DropdownMenuItem onSelect={() => toast.info('PDF export will be generated by the server once the backend is connected. Use Print → Save as PDF for now.')}>PDF</DropdownMenuItem>
                </DropdownMenuContent>
              </DropdownMenu>
            ) : null}
          </>
        }
      />
      {filters ? <div className="no-print mb-5 flex flex-wrap items-end gap-3 rounded-lg border border-border bg-surface p-3">{filters}</div> : null}
      {view === 'screen' ? <div className="grid gap-6">{children}</div> : document}
    </>
  )
}

export function FilterField({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <label className="grid gap-1">
      <span className="text-xs font-medium text-ink-muted">{label}</span>
      {children}
    </label>
  )
}
